// 合成 ECELL 记录保留实机字段布局，替换位置标识，不提交用户原始采样。
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const source = fs.readFileSync(path.resolve(__dirname,'../../package/vendor/luci-app-5gmodem/htdocs/luci-static/resources/modem5g/cellular_v1.js'),'utf8');
const c = new Function('baseclass',source)({extend:value=>value});
const serving = ['11','000000001','000001','460','11','321','55','65','255','255','11','82','255','','640000'];
const neighbor = pci => ['11','00FFFFFFF','FFFFFFF','','',String(pci),'42','62','255','255','','55','255','','640000'];
const record = rows => ({code:0,output:'+ECELL: '+rows.length+','+rows.map(row=>row.join(',')).join(',')+'\r\nOK'});
const rows = c.parseCells(record([serving,...[111,222,333,444].map(neighbor)]));
assert.equal(rows.length,5);
assert.equal(rows[0].serving,true);
assert.deepEqual([rows[0].pci,rows[0].arfcn,rows[0].rsrp,rows[0].rsrq,rows[0].sinr],[321,640000,-101,-10.5,18]);
assert.deepEqual(rows[0].bandCandidates,[77,78]);
assert.equal(rows[0].bandNo,null);
assert.deepEqual([rows[1].rsrp,rows[1].rsrq,rows[1].sinr],[-114,-12,4.5]);
assert.equal(rows[1].serving,false);
const missing=[...serving];missing[6]='';missing[7]='255';missing[11]='';
assert.deepEqual(c.parseCells(record([missing])).map(row=>[row.rsrp,row.rsrq,row.sinr]),[[null,null,null]]);
const missingPCI=[...serving];missingPCI[5]='';assert.deepEqual(c.parseCells(record([missingPCI])),[]);
assert.deepEqual(c.parseCells({output:'+ECELL: 2,'+serving.join(',')}),[]);
assert.deepEqual(c.parseCells({...record([serving]),code:5}),[]);
assert.deepEqual(c.maskBands('0000000500000000'),[1,3]);
assert.deepEqual(c.maskBands('000000000000000000002000'),[78]);
assert.deepEqual(c.maskBands('880800d5000027a0'),[1,3,5,7,8,20,28,32,38,40,41,42,43,46]);
assert.deepEqual(c.maskBands('080800d5000001a000003c00'),[1,3,5,7,8,20,28,38,40,41,75,76,77,78]);
assert.equal(c.maskBands('bad-mask'),null);
const masks=c.lockMasks('lte band info = 0000000500000000\nnr band info = 000000000000000000002000\nlte band info = 880800d5000027a0\nnr band info = 080800d5000001a000003c00');
assert.deepEqual(masks.current,{lte:[1,3],nr:[78]});
assert.equal(masks.supported.nr.length,14);
console.log('PASS ECELL: 5 rows, NR units, missing fields and overlap; masks: 32-bit word order and all supported bands');
